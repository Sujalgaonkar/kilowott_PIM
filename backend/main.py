@app.post("/api/proposals/{proposal_id}/review", response_model=ProposedChange)
async def review_proposal(proposal_id: str, payload: ProposalReviewRequest):
    """
    Review, approve, or reject an agent proposal.
    Enforces human-in-the-loop: changes are never applied to products without explicit approval.
    """
    try:
        updated_proposal = store.review_proposal(
            proposal_id=proposal_id,
            status=payload.status,
            edited_value=payload.edited_value
        )
    except KeyError:
        raise HTTPException(status_code=404, detail="Proposal not found")

    # If approved by the user, apply to product and synchronize
    if payload.status == "approved":
        product = store.get_product(updated_proposal.productId)
        if product:
            if updated_proposal.field == "description":
                product.description = updated_proposal.proposed
            else:
                product.attributes[updated_proposal.field] = updated_proposal.proposed

            product.sync_status = "pending"
            store.update_product(product)

            # Synchronize with WooCommerce adapter
            adapter = get_woocommerce_adapter()
            sync_res = await adapter.sync_product(product, operation=f"update {updated_proposal.field}")
            store.add_sync_result(sync_res)

            if sync_res.status == "success":
                product.sync_status = "synced"
            else:
                product.sync_status = "failed"
            store.update_product(product)

    return updated_proposal

@app.post("/api/agents/runs", response_model=AgentRun)
async def submit_agent_task(payload: SubmitTaskRequest):
    """
    Submit a task to the LangGraph multi-agent orchestrator.
    Runs asynchronously and logs all agent events in the timeline.
    """
    task_text = payload.task.strip()
    if not task_text:
        raise HTTPException(status_code=400, detail="Task description cannot be empty")

    run = start_agent_task_background(task_text)
    return run

