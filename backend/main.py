@app.post("/api/sync", response_model=List[SyncResult])
async def synchronize_pending_products():
    """
    Explicitly trigger synchronization for all products with pending changes.
    """
    adapter = get_woocommerce_adapter()
    pending_products = [p for p in store.get_products() if p.sync_status == "pending"]
    results: List[SyncResult] = []

    for product in pending_products:
        res = await adapter.sync_product(product, operation="batch sync")
        store.add_sync_result(res)
        results.append(res)
        if res.status == "success":
            product.sync_status = "synced"
        else:
            product.sync_status = "failed"
        store.update_product(product)

    return results
