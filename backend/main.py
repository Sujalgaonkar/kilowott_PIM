logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s"
)
logger = logging.getLogger("pim.api")

@asynccontextmanager
async def lifespan(app: FastAPI):
    adapter = get_woocommerce_adapter()
    conn_info = await adapter.test_connection()
    logger.info(f"PIM Backend started. Adapter mode: {conn_info.get('mode')}")
    yield
    logger.info("PIM Backend shutting down.")

app = FastAPI(
    title="PIM Agents API",
    description="Multi-agent Product Information Management backend powered by FastAPI & LangGraph",
    version="1.0.0",
    lifespan=lifespan,
)

# CORS middleware for React frontend integration
app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.cors_origins,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

